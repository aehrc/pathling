package au.csiro.pathling.operations.bulksubmit;

import static org.assertj.core.api.Assertions.assertThat;

import java.util.Map;
import java.util.Optional;
import java.util.UUID;
import org.junit.jupiter.api.Test;

/**
 * Tests for the server-generated staging identifier of a {@link Submission}.
 *
 * @author John Grimes
 */
class SubmissionTest {

  private static final SubmitterIdentifier SUBMITTER_A =
      new SubmitterIdentifier("urn:test", "hospital-a");
  private static final SubmitterIdentifier SUBMITTER_B =
      new SubmitterIdentifier("urn:test", "hospital-b");

  // The staging identifier names the staging directory and the result registry entry, so it must be
  // generated by the server rather than taken from the client-chosen submission identifier.
  @Test
  void createPendingAssignsServerGeneratedStagingId() {
    final Submission submission = Submission.createPending("S1", SUBMITTER_A, Optional.empty());

    assertThat(submission.stagingId()).isNotEqualTo("S1");
    assertThat(UUID.fromString(submission.stagingId()).toString())
        .isEqualTo(submission.stagingId());
  }

  // Two submitters may legitimately use the same submission identifier. Their submissions must
  // still be staged and registered separately.
  @Test
  void submissionsWithSameIdFromDifferentSubmittersHaveDifferentStagingIds() {
    final Submission first = Submission.createPending("S1", SUBMITTER_A, Optional.of("alice"));
    final Submission second = Submission.createPending("S1", SUBMITTER_B, Optional.of("mallory"));

    assertThat(first.stagingId()).isNotEqualTo(second.stagingId());
  }

  // Every copy made while the submission moves through its lifecycle keeps the staging identifier,
  // so that files staged early in the lifecycle remain reachable later on.
  @Test
  void copiesPreserveStagingId() {
    final Submission submission = Submission.createPending("S1", SUBMITTER_A, Optional.empty());
    final ManifestJob manifestJob =
        ManifestJob.createPending("mj-1", "https://example.org/manifest.json", null, null);
    final String stagingId = submission.stagingId();

    final Submission withJob = submission.withManifestJob(manifestJob);
    assertThat(withJob.stagingId()).isEqualTo(stagingId);
    assertThat(withJob.withState(SubmissionState.PROCESSING).stagingId()).isEqualTo(stagingId);
    assertThat(
            withJob
                .withUpdatedManifestJob("mj-1", manifestJob.withState(ManifestJobState.PROCESSING))
                .stagingId())
        .isEqualTo(stagingId);
    assertThat(withJob.withoutManifestJob("mj-1").stagingId()).isEqualTo(stagingId);
    assertThat(withJob.withMetadata(new SubmissionMetadata(Map.of("label", "x"))).stagingId())
        .isEqualTo(stagingId);
    assertThat(withJob.withError("failed").stagingId()).isEqualTo(stagingId);
  }
}
