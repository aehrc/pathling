/**
 * Ticket 12: T100o's generated-code check, repeated over the Parquet on FHIR layout with and without
 * the canonical annotations, and extended with the equality and the inequality alone for T096c.
 * For each expression, with common-subexpression elimination on and off, it prints whether the
 * projection is part of whole-stage code generation, the calls of the canonicalisation in the
 * physical plan and the call sites in the generated code, the subexpression functions, the size of
 * the code, and, where the projection falls back, why.
 *
 * <p>Usage: Codegen <directory holding Observation> [directory to dump the generated code into].
 */
import au.csiro.pathling.library.PathlingContext;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.regex.Pattern;
import org.apache.spark.sql.Dataset;
import org.apache.spark.sql.Row;
import org.apache.spark.sql.SparkSession;
import org.apache.spark.sql.catalyst.expressions.BindReferences;
import org.apache.spark.sql.catalyst.expressions.Expression;
import org.apache.spark.sql.catalyst.expressions.codegen.CodegenContext;
import org.apache.spark.sql.catalyst.expressions.codegen.CodegenFallback;
import org.apache.spark.sql.catalyst.expressions.codegen.ExprCode;
import org.apache.spark.sql.catalyst.expressions.codegen.GenerateUnsafeProjection;
import org.apache.spark.sql.execution.ProjectExec;
import org.apache.spark.sql.execution.SparkPlan;
import org.apache.spark.sql.execution.WholeStageCodegenExec;
import org.apache.spark.sql.internal.SQLConf;
import org.apache.spark.sql.types.ArrayType;
import org.apache.spark.sql.types.DataType;
import org.apache.spark.sql.types.MapType;
import org.apache.spark.sql.types.StructField;
import org.apache.spark.sql.types.StructType;
import scala.Tuple3;
import scala.jdk.javaapi.CollectionConverters;

/**
 * Where the projection is part of whole-stage code generation, the code examined is the stage's,
 * from {@code codegenToSeq}. Where it is not, Spark evaluates the projection with an {@code
 * UnsafeProjection} generated by {@code GenerateUnsafeProjection}, with elimination as configured,
 * and the probe generates the same code. Call sites are counted by the name each carries for its
 * error message.
 */
public class Codegen {

  /** How a call site of the canonicalisation is named in generated code, for its error message. */
  private static final String CALL_SITE = "\"quantity_canonical (";

  public static void main(final String[] args) throws Exception {
    final SparkSession spark =
        SparkSession.builder()
            .master("local[4]")
            .config("spark.ui.enabled", "false")
            .getOrCreate();
    spark.sparkContext().setLogLevel("ERROR");
    final PathlingContext pc = PathlingContext.create(spark);
    final Dataset<Row> obs = spark.read().parquet(args[0] + "/Observation");
    final String dump = args.length > 1 ? args[1] : null;
    final String q = "value.ofType(Quantity)";
    final List<String> exprs =
        List.of(
            q,
            q + " > 1 'mg/dL'",
            q + " > 1 'mg/dL' and " + q + " < 1000 'mg/dL'",
            q + " > 1 'mg/dL' and " + q + " < 1000 'mg/dL' and " + q + " != 50 'mg/dL'",
            q + " = 50 'mg/dL'",
            q + " != 50 'mg/dL'",
            "(" + q + " = 50 'mg/dL').not()");
    for (final boolean cse : List.of(true, false)) {
      spark.conf().set("spark.sql.subexpressionElimination.enabled", String.valueOf(cse));
      int n = 0;
      for (final String e : exprs) {
        n++;
        final Dataset<Row> query = obs.select(pc.fhirPathToColumn("Observation", e).alias("x"));
        final SparkPlan plan = query.queryExecution().executedPlan();
        final String planText = plan.toString();
        final int planCalls = count(planText, "quantity_canonical(");
        final boolean wholeStage = plan instanceof WholeStageCodegenExec;
        final String text;
        int maxMethod = -1;
        String reason = "-";
        if (wholeStage) {
          final StringBuilder code = new StringBuilder();
          for (final Tuple3<String, String, ?> stage :
              CollectionConverters.asJava(query.queryExecution().debug().codegenToSeq())) {
            code.append(stage._2());
            final Object stats = stage._3();
            maxMethod =
                Math.max(
                    maxMethod, (int) stats.getClass().getMethod("maxMethodCodeSize").invoke(stats));
          }
          text = code.toString();
        } else {
          final ProjectExec project = (ProjectExec) plan;
          reason = fallbackReason(project);
          // AttributeSeq is a class of a Scala package object, which Java cannot name.
          final Object input =
              Class.forName("org.apache.spark.sql.catalyst.expressions.package$AttributeSeq")
                  .getConstructor(scala.collection.immutable.Seq.class)
                  .newInstance(project.child().output());
          final java.lang.reflect.Method bind =
              BindReferences.class.getMethod(
                  "bindReference", Expression.class, input.getClass(), boolean.class);
          final List<Expression> bound = new ArrayList<>();
          for (final Object x : CollectionConverters.asJava(project.projectList())) {
            bound.add((Expression) bind.invoke(null, x, input, false));
          }
          final CodegenContext ctx = new CodegenContext();
          final ExprCode eval =
              GenerateUnsafeProjection.createCode(
                  ctx, CollectionConverters.asScala(bound).toSeq(), cse);
          text = ctx.declareAddedFunctions() + "\n" + eval.code();
        }
        if (dump != null) {
          Files.createDirectories(Path.of(dump));
          Files.writeString(Path.of(dump, "expr" + n + (cse ? "-cse" : "-nocse") + ".java"), text);
        }
        System.out.println(
            "CODEGEN cse="
                + cse
                + " wholeStage="
                + wholeStage
                + " planCalls="
                + planCalls
                + " codeCalls="
                + count(text, CALL_SITE)
                + " matchers="
                + count(text, ".matcher(")
                + " subexprFns="
                + Pattern.compile("private void \\w*subExpr_\\d+\\(").matcher(text).results().count()
                + " chars="
                + text.length()
                + " maxMethodBytes="
                + maxMethod
                + " fallback="
                + reason
                + " :: "
                + e);
      }
    }
    spark.stop();
  }

  /**
   * Says why a projection is not part of whole-stage code generation: the widest nested type in it
   * against the limit, the distinct kinds of expression in it that cannot generate code, and the
   * number of canonicalisation calls beneath them, which Spark interprets.
   */
  private static String fallbackReason(final ProjectExec project) {
    final int maxFields = SQLConf.get().wholeStageMaxNumFields();
    int widest = 0;
    int interpreted = 0;
    final java.util.Set<String> fallbacks = new java.util.TreeSet<>();
    final List<Expression> pending = new ArrayList<>();
    for (final Object x : CollectionConverters.asJava(project.projectList())) {
      pending.add((Expression) x);
    }
    while (!pending.isEmpty()) {
      final Expression x = pending.remove(pending.size() - 1);
      widest = Math.max(widest, nestedFields(x.dataType()));
      if (x instanceof CodegenFallback) {
        // Everything beneath an expression that cannot generate code is interpreted.
        fallbacks.add(x.getClass().getSimpleName());
        interpreted += count(x.toString(), "quantity_canonical(");
      } else {
        pending.addAll(CollectionConverters.asJava(x.children()));
      }
    }
    return "widestNestedFields="
        + widest
        + "/max"
        + maxFields
        + ",codegenFallbacks="
        + fallbacks
        + ",interpretedCalls="
        + interpreted;
  }

  /** Counts the nested fields of a type as whole-stage code generation does. */
  private static int nestedFields(final DataType type) {
    if (type instanceof final StructType struct) {
      int n = 0;
      for (final StructField f : struct.fields()) {
        n += nestedFields(f.dataType());
      }
      return n;
    } else if (type instanceof final ArrayType array) {
      return nestedFields(array.elementType());
    } else if (type instanceof final MapType map) {
      return nestedFields(map.keyType()) + nestedFields(map.valueType());
    }
    return 1;
  }

  private static int count(final String text, final String token) {
    return text.split(Pattern.quote(token), -1).length - 1;
  }
}
