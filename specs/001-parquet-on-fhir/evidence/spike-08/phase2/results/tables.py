"""Writes phase 2's per-type tables from the result JSON, on pooled minimums as pooled_phases.py computes them."""
import glob, json, sys

R = sys.argv[1]
SRC = ("json", "xml-lines", "xml-bundles", "xml-bundles-txn")
TYPES = ("Patient", "Condition", "Encounter", "Observation")
PH = (("fit", "fitMs", "fitPlanPy4jMs"), ("encode", "encodeMs", None), ("decode", "decodeMs", "decodePlanPy4jMs"))


def load(pattern):
    out = {}
    for f in glob.glob(f"{R}/{pattern}/phases-*.json"):
        d = json.load(open(f))
        out.setdefault(d["source"], []).append(d["results"])
    return out


def pmin(runs, t, key, sub=None):
    xs = []
    for r in runs:
        s = r[t][key]["samples"]
        if sub and sub in r[t]:
            s = [a - b for a, b in zip(s, r[t][sub]["samples"])]
        xs += s
    return min(xs)


bar, a1, a2 = load("phases-pof-switch-26d7332"), load("p2-a0-r1-514f8f8"), load("p2-a0-r2-514f8f8")
cands = (("A+", "p2-aplus-r?-514f8f8", True), ("B", "p2-b-r?-514f8f8", False), ("A-variant", "p2-avariant-r?-514f8f8", True))
s = lambda ms: f"{ms / 1000:.2f}"
print("# Phase 2 timings at size l, per type\n")
print("Generated by `tables.py` from the result files in this directory and phase 1's bar label (`../../results/phases-pof-switch-26d7332/`).")
print("Every figure is a pooled minimum in seconds: the bar and each A0 label pool their extensions-off and")
print("extensions-on runs (ten samples), and a candidate pools its `r1` and `r2` labels (ten samples). A ratio is")
print("the candidate's pooled minimum over the reference's. \"py4j removed\" subtracts the candidate's own py4j")
print("plan-building time sample by sample before the minimum is taken, for fit and decode; encode has none.")
print("B builds no plan in Python, so it has no such column. A-variant ran on JSON only.\n")
print("## A0 in this batch\n")
print("| Source | Type | Phase | Bar | A0 r1 | A0 r2 | r1/bar | r2/bar | r2/r1 |")
print("|---|---|---|---|---|---|---|---|---|")
for src in SRC:
    for t in TYPES:
        for name, key, _ in PH:
            b, x, y = pmin(bar[src], t, key), pmin(a1[src], t, key), pmin(a2[src], t, key)
            print(f"| {src} | {t} | {name} | {s(b)} | {s(x)} | {s(y)} | {x/b:.2f} | {y/b:.2f} | {y/x:.2f} |")
for cname, pat, py4j in cands:
    c = load(pat)
    print(f"\n## {cname} (`{pat}`)\n")
    hdr = "| Source | Type | Phase | Bar | A0 r1 | A0 r2 | " + cname + " | /bar | /A0 r1 | /A0 r2 |"
    sep = "|---|---|---|---|---|---|---|---|---|---|"
    if py4j:
        hdr += " " + cname + ", py4j removed | /bar | /A0 r1 | /A0 r2 |"
        sep += "---|---|---|---|"
    print(hdr)
    print(sep)
    for src in SRC:
        if src not in c:
            continue
        for t in TYPES:
            for name, key, sub in PH:
                b, x, y, v = pmin(bar[src], t, key), pmin(a1[src], t, key), pmin(a2[src], t, key), pmin(c[src], t, key)
                row = f"| {src} | {t} | {name} | {s(b)} | {s(x)} | {s(y)} | {s(v)} | {v/b:.2f} | {v/x:.2f} | {v/y:.2f} |"
                if py4j:
                    w = pmin(c[src], t, key, sub) if sub else v
                    row += f" {s(w)} | {w/b:.2f} | {w/x:.2f} | {w/y:.2f} |"
                print(row)
messy = {k: load(f"p2-messy-{k}-514f8f8") for k in ("pathling", "aplus", "avariant", "b")}
print("\n## Messy JSON, under `drop` (five samples per label)\n")
print("| Type | Phase | A0 | A+ | A+/A0 | A+, py4j removed | /A0 | A-variant | A-variant/A0 | A-variant, py4j removed | /A0 | B | B/A0 |")
print("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
for t in TYPES:
    for name, key, sub in PH:
        a = pmin(messy["pathling"]["json"], t, key)
        cells = []
        for k in ("aplus", "avariant"):
            v = pmin(messy[k]["json"], t, key)
            w = pmin(messy[k]["json"], t, key, sub) if sub else v
            cells += [s(v), f"{v/a:.2f}", s(w), f"{w/a:.2f}"]
        v = pmin(messy["b"]["json"], t, key)
        cells += [s(v), f"{v/a:.2f}"]
        print(f"| {t} | {name} | {s(a)} | " + " | ".join(cells) + " |")
